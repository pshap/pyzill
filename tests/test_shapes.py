"""The contract between Zillow's payload and the parsers that read it.

Zillow's payloads are not committed: they hold real listing data. What *is*
committed is a shape -- the set of key paths in a captured payload, with no
values -- under ``tests/shapes/``. A shape names the fields Zillow sent and
holds nothing about what is in them, so it can be reviewed and diffed like
any other source file.

The baselines are the contract: this module says which of Zillow's fields
the parsers depend on, and checks that the baselines still carry them. A
field Zillow renames shows up here as a failure to look at, instead of as a
column that quietly fills with nulls.

The baselines are regenerated by ``scripts/capture_fixture.py``, which writes
one next to every capture.
"""

import importlib.util
import json
from pathlib import Path
from types import ModuleType
from typing import Any

import pytest

SHAPES = Path(__file__).parent / "shapes"
FIXTURES = Path(__file__).parent / "fixtures"
_CAPTURE_SCRIPT = Path(__file__).resolve().parents[1] / "scripts" / "capture_fixture.py"

# The search fields the parsers read, as paths inside a result row. Every one
# of them was present in all three search captures, so their absence means
# Zillow changed the payload rather than that a row happened to omit them.
REQUIRED_SEARCH_PATHS: tuple[str, ...] = (
    "zpid",
    "price",
    "priceLabel",
    "beds",
    "baths",
    "area",
    "address",
    "addressState",
    "latLong.latitude",
    "latLong.longitude",
    "statusText",
    "statusType",
    "detailUrl",
    "imgSrc",
    "hdpData.homeInfo.price",
    "hdpData.homeInfo.bedrooms",
    "hdpData.homeInfo.bathrooms",
    "hdpData.homeInfo.livingArea",
    "hdpData.homeInfo.streetAddress",
    "hdpData.homeInfo.city",
    "hdpData.homeInfo.state",
    "hdpData.homeInfo.zipcode",
    "hdpData.homeInfo.homeType",
    "hdpData.homeInfo.homeStatus",
    "hdpData.homeInfo.daysOnZillow",
    "hdpData.homeInfo.listing_sub_type",
    "hdpData.homeInfo.rentZestimate",
    "hdpData.homeInfo.zpid",
    "hdpData.homeInfo.latitude",
    "hdpData.homeInfo.longitude",
)

# The detail fields the property-detail parser reads.
REQUIRED_DETAIL_PATHS: tuple[str, ...] = (
    "zpid",
    "price",
    "bedrooms",
    "bathrooms",
    "livingAreaValue",
    "livingArea",
    "address.streetAddress",
    "address.city",
    "address.state",
    "address.zipcode",
    "resoFacts.yearBuilt",
    "resoFacts.lotSize",
    "resoFacts.hoaFeeTotal",
    "lotAreaValue",
    "lotAreaUnits",
    "lotSize",
    "monthlyHoaFee",
    "photoCount",
    "originalPhotos",
    "responsivePhotos",
    "homeType",
    "latitude",
    "longitude",
    "description",
)

# The apartment payload is handed back as it arrived, so only the containers
# the reader navigates are part of the contract.
REQUIRED_APARTMENT_PATHS: tuple[str, ...] = ("building", "building.address", "viewer")


def _shape(name: str) -> set[str]:
    path = SHAPES / f"{name}.txt"
    if not path.exists():
        pytest.fail(f"missing shape baseline {path}; run scripts/capture_fixture.py to regenerate it")
    return {line for line in path.read_text(encoding="utf-8").split("\n") if line}


@pytest.fixture(scope="module")
def capture() -> ModuleType:
    """Load scripts/capture_fixture.py as a module (scripts/ is not a package)."""
    spec = importlib.util.spec_from_file_location("capture_fixture", _CAPTURE_SCRIPT)
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.mark.parametrize("name", ["search_sale", "search_rent", "search_sold"])
def test_the_search_baseline_still_carries_the_fields_the_parser_reads(name: str) -> None:
    """A field Zillow renamed must fail here, not fill a column with nulls."""
    shape = _shape(name)
    missing = [
        path
        for path in REQUIRED_SEARCH_PATHS
        if not any(f"{row}.{path}" in shape for row in ("mapResults[]", "listResults[]"))
    ]
    assert not missing, (
        f"{name}: Zillow's payload no longer carries {missing}. "
        "Re-capture with scripts/capture_fixture.py and update the parser."
    )


def test_the_detail_baseline_still_carries_the_fields_the_parser_reads() -> None:
    shape = _shape("detail_home")
    missing = [path for path in REQUIRED_DETAIL_PATHS if path not in shape]
    assert not missing, (
        f"detail_home: Zillow's payload no longer carries {missing}. "
        "Re-capture with scripts/capture_fixture.py and update the parser."
    )


def test_the_apartment_baseline_still_carries_the_containers_the_reader_navigates() -> None:
    shape = _shape("detail_apartment")
    missing = [path for path in REQUIRED_APARTMENT_PATHS if path not in shape]
    assert not missing, (
        f"detail_apartment: Zillow's payload no longer carries {missing}. "
        "Re-capture with scripts/capture_fixture.py and update the parser."
    )


@pytest.mark.parametrize(
    ("name", "minimum_paths"),
    [
        ("search_sale", 100),
        ("search_rent", 100),
        ("search_sold", 100),
        ("detail_home", 400),
        ("detail_apartment", 300),
    ],
)
def test_a_baseline_has_not_been_written_over_by_a_trivial_payload(name: str, minimum_paths: int) -> None:
    """A baseline is a whole payload's shape, not a handful of keys.

    A capture script that is pointed at a small payload by mistake would
    otherwise replace the contract with something that checks nothing.
    """
    assert len(_shape(name)) >= minimum_paths, (
        f"{name}: the baseline holds {len(_shape(name))} paths, expected at least {minimum_paths}. "
        "It was probably overwritten by a capture of a trivial payload."
    )


@pytest.mark.parametrize("name", ["search_sale", "search_rent", "search_sold", "detail_home", "detail_apartment"])
def test_a_captured_payload_still_has_the_shape_that_was_recorded(name: str, capture: ModuleType) -> None:
    """A fresh capture must still have the shape that was committed.

    This is the drift alarm: it runs when a live capture is on disk, and it
    is the check that says "Zillow changed the payload" before a user does.
    """
    fixture = FIXTURES / f"{name}.json"
    if not fixture.exists():
        pytest.skip(f"{name} not captured yet; run scripts/capture_fixture.py --confirm")
    payload: Any = json.loads(fixture.read_text(encoding="utf-8"))

    recorded = _shape(name)
    captured = capture.shape_of(payload)
    assert captured == recorded, (
        f"{name}: Zillow's payload changed shape. "
        f"Missing: {sorted(recorded - captured)[:10]}. "
        f"New: {sorted(captured - recorded)[:10]}. "
        "Update the parser, then re-record the baseline with scripts/capture_fixture.py."
    )
